const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * Android hardening that Expo does not apply by default.
 *
 * 1. Forbids cleartext HTTP. The previous build shipped
 *    usesCleartextTraffic="true", which would let a hostile network
 *    downgrade the signaling connection for a camera pointed at a child.
 * 2. Marks the app as non-backupable, so a device backup never carries
 *    the pairing secret off the phone.
 */

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBabyfunkenAndroid.js. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

/** Writes res/xml/network_security_config.xml into the generated project. */
const withNetworkSecurityConfigFile = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), NETWORK_SECURITY_CONFIG);
      return cfg;
    },
  ]);

const withManifestHardening = (config) =>
  withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);

    app.$['android:usesCleartextTraffic'] = 'false';
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    app.$['android:allowBackup'] = 'false';
    app.$['android:fullBackupContent'] = 'false';

    return cfg;
  });

module.exports = (config) => withManifestHardening(withNetworkSecurityConfigFile(config));
